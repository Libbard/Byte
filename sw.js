/*
 * ═══════════════════════════════════════════════════════════════
 *  عاملُ خدمةٍ ينتحر — مفتاحُ إطفاءِ Byte
 * ═══════════════════════════════════════════════════════════════
 *  🔴 **بلا هذا الملفّ لا يرى نصفُ الطلاب صفحةَ الوداع إطلاقاً.**
 *
 *  مستودعُ Byte كان يخدم الموقعَ كاملاً بعاملِ خدمةٍ اسمُه `byte-v69`
 *  (قِيس حيّاً 2026-08-09)، واستراتيجيتُه **stale-while-revalidate**:
 *  يردّ من الكاش **أوّلاً** ثمّ يحدّثه في الخلفية. فلو أفرغنا المستودعَ
 *  ووضعنا `404.html` وحدَها، لظلّ العاملُ المسجَّلُ في متصفّح كلِّ طالبٍ
 *  زار Byte مرّةً **يخدم النسخةَ القديمة من ذاكرته** — موقعاً ميّتاً
 *  يعمل، ولا تحويلةَ ولا رسالة. والمثبِّتون كتطبيقٍ (PWA) أسوأُ حالاً:
 *  لا يفتحون المتصفّحَ أصلاً.
 *
 *  والمخرجُ أن **يُترك `sw.js` في مكانه** بهذا المحتوى. المتصفّحُ يفحص
 *  ملفَّ العامل عند كلِّ تنقّلٍ (وبحدٍّ أقصى كلَّ ٢٤ ساعة)، فيجد بايتاتٍ
 *  مختلفةً فيُنصّب هذه النسخة — وهي تفعل ثلاثةَ أشياءَ ثمّ تختفي:
 *
 *    ١) `skipWaiting` — لا تنتظر إغلاقَ كلِّ التبويبات.
 *    ٢) تمحو **كلَّ** الكاشات وتُلغي تسجيلَ نفسها.
 *    ٣) وتعيد تحميلَ كلِّ صفحةٍ مفتوحةٍ — فتصل إلى `404.html` الحقيقية
 *       وتقع التحويلة.
 *
 *  ⚠️ **ولا تحذف هذا الملفَّ من مستودع Byte أبداً.** حذفُه يجعل
 *     `/Byte/sw.js` يردّ 404، وبعضُ المتصفحات تُبقي العاملَ القديمَ
 *     مسجّلاً عند فشل الجلب — أي أن الحذفَ **يُخلّد** ما نريد قتلَه.
 */

self.addEventListener('install', function () {
  self.skipWaiting();
});

self.addEventListener('activate', function (event) {
  event.waitUntil((async function () {
    try {
      var keys = await caches.keys();
      await Promise.all(keys.map(function (k) { return caches.delete(k); }));
    } catch (e) {}

    try { await self.registration.unregister(); } catch (e) {}

    /* ⚠️ `client.navigate` لا تعمل إلا على عميلٍ من نوع window، وقد
       ترفضها بعضُ المتصفحات — فالفشلُ يُبتلع، ويكفي أن الكاشَ زال
       والتسجيلَ أُلغي: التحديثُ التالي يصل من الشبكة حتماً. */
    try {
      var clients = await self.clients.matchAll({ type: 'window' });
      for (var i = 0; i < clients.length; i++) {
        try { await clients[i].navigate(clients[i].url); } catch (e) {}
      }
    } catch (e) {}
  })());
});

